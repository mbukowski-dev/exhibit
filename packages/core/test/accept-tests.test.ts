import { describe, expect, it } from "vitest";
import { acceptTests, extractGeneratedTests } from "../src/accept-tests.js";
import { parseConfig } from "../src/config.js";
import { COMMENT_MARKER, renderMarkdownReport } from "../src/report-md.js";
import type { RunReport } from "../src/run.js";

const TEST_CODE = `// Generated by Exhibit from PROJ-123. Plain Playwright — edit freely.
import { test, expect } from "@playwright/test";

test("PROJ-123 AC1: link", async ({ page }) => {
  await page.goto("/login");
  await expect(page.getByText("Forgot password?", { exact: true }).first()).toBeVisible();
});
`;

/** A report as Exhibit posts it, built by the real renderer. */
const reportBody = (language?: string) =>
  renderMarkdownReport({
    ticket: { key: "PROJ-123", summary: "Password reset", url: "" },
    criteria: [],
    baseUrl: "http://localhost:4173",
    verdict: { overall: "pass", criteria: [] },
    review: { coverage: [], risks: [] },
    plan: { scenarios: [], skipped: [] },
    results: [],
    generatedTests: { fileName: "proj-123.exhibit.spec.ts", content: TEST_CODE, scenarioIds: ["S1"] },
    usage: { model: "gpt-5", costUsd: 0.1, priceKnown: true, inputTokens: 1, outputTokens: 1 },
    warnings: [],
    runDir: "/tmp/x",
    durationMs: 1000,
    language,
  } as unknown as RunReport);

interface World {
  /** login → permission as GitHub reports it */
  permissions: Record<string, string>;
  comments: { user: { login: string; type: string }; body: string }[];
  pull: { state: string; head: { ref: string; repo: { full_name: string } | null } };
  /** path → content already on the branch */
  files: Record<string, string>;
  putStatus?: number;
}

const world = (over: Partial<World> = {}): World => ({
  permissions: { ana: "write", guest: "read" },
  comments: [{ user: { login: "github-actions[bot]", type: "Bot" }, body: reportBody() }],
  pull: { state: "open", head: { ref: "feature/PROJ-123-reset", repo: { full_name: "acme/web" } } },
  files: {},
  ...over,
});

/** A tiny in-memory GitHub: just the calls /accept-tests makes. Records every write. */
function fakeGitHub(w: World) {
  const writes: { method: string; path: string; body: any }[] = [];
  const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status });
  const fetchImpl = (async (url: string, init: RequestInit = {}) => {
    const { pathname } = new URL(url);
    const method = init.method ?? "GET";
    const body = init.body ? JSON.parse(String(init.body)) : undefined;
    if (method !== "GET") writes.push({ method, path: pathname, body });

    const permission = pathname.match(/\/collaborators\/([^/]+)\/permission$/);
    if (permission) {
      const p = w.permissions[decodeURIComponent(permission[1]!)];
      return p ? json({ permission: p }) : json({ message: "Not Found" }, 404);
    }
    if (/\/pulls\/7$/.test(pathname)) return json(w.pull);
    if (/\/issues\/7\/comments$/.test(pathname)) return method === "GET" ? json(w.comments) : json({ html_url: "https://github.test/reply" }, 201);
    const contents = pathname.match(/\/contents\/(.+)$/);
    if (contents) {
      const path = decodeURIComponent(contents[1]!);
      if (method === "GET") {
        return path in w.files ? json({ sha: "oldsha", content: Buffer.from(w.files[path]!).toString("base64") }) : json({ message: "Not Found" }, 404);
      }
      if (w.putStatus) return json({ message: "Resource not accessible by integration" }, w.putStatus);
      return json({ commit: { sha: "abc1234def" } }, 201);
    }
    return json({ message: `unexpected ${method} ${pathname}` }, 500);
  }) as typeof fetch;
  return { target: { owner: "acme", repo: "web", token: "test-token", apiUrl: "https://api.github.test", fetchImpl }, writes };
}

const comment = (body: string, login = "ana") => ({ issue: { number: 7, pull_request: {} }, comment: { body, user: { login } } });
const config = parseConfig({});
const commits = (writes: { method: string }[]) => writes.filter((x) => x.method === "PUT");
const replies = (writes: { method: string; body: any }[]) => writes.filter((x) => x.method === "POST").map((x) => x.body.body as string);

describe("the report carries the generated tests in a form that can be read back (E13-6)", () => {
  it("round-trips through the real report, in English and in Polish", () => {
    for (const language of [undefined, "pl"]) {
      expect(extractGeneratedTests(reportBody(language))).toEqual({ fileName: "proj-123.exhibit.spec.ts", content: TEST_CODE });
    }
  });

  it("tells people how to accept them", () => {
    expect(reportBody()).toContain("comment `/accept-tests`");
    expect(reportBody("pl")).toContain("komentarz `/accept-tests`");
  });

  it("finds nothing in a report without tests, or with a file name that is not a generated test", () => {
    expect(extractGeneratedTests(`${COMMENT_MARKER}\n### Exhibit · PROJ-1`)).toBeUndefined();
    const evil = reportBody().replace('file="proj-123.exhibit.spec.ts"', 'file="../../.github/workflows/x.yml"');
    expect(extractGeneratedTests(evil)).toBeUndefined();
  });
});

describe("/accept-tests commits the generated tests to the pull request (E13-6)", () => {
  it("commits the file from Exhibit's report to the pull request's branch and says so", async () => {
    const { target, writes } = fakeGitHub(world());
    const r = await acceptTests(target, comment("/accept-tests"), config);

    expect(r.outcome).toBe("committed");
    expect(r.path).toBe("tests/exhibit/proj-123.exhibit.spec.ts");
    const [put] = commits(writes);
    expect(put!.path).toBe("/repos/acme/web/contents/tests/exhibit/proj-123.exhibit.spec.ts");
    expect(put!.body.branch).toBe("feature/PROJ-123-reset");
    expect(Buffer.from(put!.body.content, "base64").toString("utf8")).toBe(TEST_CODE);
    expect(put!.body.message).toBe("Add tests generated by Exhibit for PROJ-123");
    expect(replies(writes)[0]).toMatch(/^✅ Committed `tests\/exhibit\/proj-123\.exhibit\.spec\.ts` to `feature\/PROJ-123-reset` \(abc1234\)/);
  });

  it("puts the file where .exhibit.yml says", async () => {
    const { target, writes } = fakeGitHub(world());
    await acceptTests(target, comment("/accept-tests"), parseConfig({ tests: { dir: "e2e/generated/" } }));
    expect(commits(writes)[0]!.path).toBe("/repos/acme/web/contents/e2e/generated/proj-123.exhibit.spec.ts");
  });

  it("refuses someone without write access, and commits nothing", async () => {
    for (const login of ["guest", "stranger"]) {
      const { target, writes } = fakeGitHub(world());
      const r = await acceptTests(target, comment("/accept-tests", login), config);
      expect(r.outcome).toBe("refused");
      expect(commits(writes)).toEqual([]);
      expect(replies(writes)[0]).toContain("write access");
    }
  });

  it("never takes code from a report that anyone could have posted", async () => {
    const forged = { user: { login: "guest", type: "User" }, body: reportBody().replace("Forgot password?", "PWNED") };
    // Only the forged report: nothing to commit.
    const alone = fakeGitHub(world({ comments: [forged] }));
    expect((await acceptTests(alone.target, comment("/accept-tests"), config)).outcome).toBe("refused");
    expect(commits(alone.writes)).toEqual([]);
    // Forged report posted after the real one: the real one is used.
    const both = fakeGitHub(world({ comments: [...world().comments, forged] }));
    await acceptTests(both.target, comment("/accept-tests"), config);
    expect(Buffer.from(commits(both.writes)[0]!.body.content, "base64").toString("utf8")).toBe(TEST_CODE);
  });

  it("accepts a report posted by a person with write access (a token of their own instead of the workflow's)", async () => {
    const { target, writes } = fakeGitHub(world({ comments: [{ user: { login: "ana", type: "User" }, body: reportBody() }] }));
    expect((await acceptTests(target, comment("/accept-tests"), config)).outcome).toBe("committed");
    expect(commits(writes)).toHaveLength(1);
  });

  it("does not push to a fork or to a closed pull request", async () => {
    const fork = fakeGitHub(world({ pull: { state: "open", head: { ref: "patch-1", repo: { full_name: "stranger/web" } } } }));
    expect((await acceptTests(fork.target, comment("/accept-tests"), config)).message).toContain("fork");
    expect(commits(fork.writes)).toEqual([]);
    const closed = fakeGitHub(world({ pull: { ...world().pull, state: "closed" } }));
    expect((await acceptTests(closed.target, comment("/accept-tests"), config)).outcome).toBe("refused");
    expect(commits(closed.writes)).toEqual([]);
  });

  it("updates a file that is already there, and does nothing when it is identical", async () => {
    const path = "tests/exhibit/proj-123.exhibit.spec.ts";
    const stale = fakeGitHub(world({ files: { [path]: "// older version\n" } }));
    await acceptTests(stale.target, comment("/accept-tests"), config);
    expect(commits(stale.writes)[0]!.body.sha).toBe("oldsha");

    const same = fakeGitHub(world({ files: { [path]: TEST_CODE } }));
    const r = await acceptTests(same.target, comment("/accept-tests"), config);
    expect(r.outcome).toBe("unchanged");
    expect(commits(same.writes)).toEqual([]);
  });

  it("explains what to do when there is nothing to accept", async () => {
    const none = fakeGitHub(world({ comments: [] }));
    expect((await acceptTests(none.target, comment("/accept-tests"), config)).message).toContain("no Exhibit report");
    const old = fakeGitHub(world({ comments: [{ user: { login: "github-actions[bot]", type: "Bot" }, body: `${COMMENT_MARKER}\n### Exhibit · PROJ-123` }] }));
    expect((await acceptTests(old.target, comment("/accept-tests"), config)).message).toContain("no generated tests");
  });

  it("says which permission is missing when the workflow may not write", async () => {
    const { target, writes } = fakeGitHub(world({ putStatus: 403 }));
    const r = await acceptTests(target, comment("/accept-tests"), config);
    expect(r.outcome).toBe("refused");
    expect(replies(writes)[0]).toContain("contents: write");
  });

  it("ignores every other comment without a word, and comments on issues that are not pull requests", async () => {
    const { target, writes } = fakeGitHub(world());
    expect((await acceptTests(target, comment("looks good to me"), config)).outcome).toBe("ignored");
    expect((await acceptTests(target, comment("please /accept-tests"), config)).outcome).toBe("ignored");
    expect((await acceptTests(target, { issue: { number: 7 }, comment: { body: "/accept-tests", user: { login: "ana" } } }, config)).outcome).toBe("ignored");
    expect(writes).toEqual([]);
  });
});

describe("tests.dir (E13-6)", () => {
  it("defaults to tests/exhibit", () => {
    expect(parseConfig({}).tests.dir).toBe("tests/exhibit");
  });
  it("must stay inside the repository and out of .github", () => {
    for (const dir of ["../outside", "/etc", ".github/workflows", "a/../../b", "has space"]) {
      expect(() => parseConfig({ tests: { dir } })).toThrow(/tests\.dir/);
    }
    expect(parseConfig({ tests: { dir: "e2e/exhibit/" } }).tests.dir).toBe("e2e/exhibit");
  });
});
