import type { ScenarioResult } from "./browser/agent.js";
import type { Scenario } from "./plan.js";

export interface GeneratedTests {
  fileName: string;
  content: string;
  scenarioIds: string[];
}

const q = (s: string) => JSON.stringify(s);

/**
 * E5-1: turns passed, replay-stable scenarios into one plain Playwright spec.
 * The output has no dependency on Exhibit; it runs with `npx playwright test`
 * against `baseURL` from the project's playwright config.
 */
export function generateTests(
  ticketKey: string,
  scenarios: Scenario[],
  results: ScenarioResult[],
): GeneratedTests | undefined {
  const usable = results.filter((r) => r.verdict === "pass" && r.replay === "stable");
  if (!usable.length) return undefined;

  const blocks = usable.map((r) => {
    const s = scenarios.find((x) => x.id === r.scenarioId)!;
    const label = `${ticketKey} ${r.acIds.join(", ") || "regression"}: ${s.title}`;
    const lines = [
      ...(s.role !== "anonymous" ? [`// Requires a logged-in "${s.role}" user — add your login here (see .exhibit.yml auth).`] : []),
      // The recorded run accepted the app's confirm/alert dialogs; unhandled, Playwright dismisses them.
      ...(r.steps.some((st) => st.dialogs?.length) ? [`page.on("dialog", (dialog) => dialog.accept());`] : []),
      `await page.goto(${q(s.startPath || "/")});`,
      ...r.steps.filter((st) => st.ok && st.code).map((st) => st.code!),
    ];
    return `test(${q(label)}, async ({ page }) => {\n${lines.map((l) => "  " + l).join("\n")}\n});`;
  });

  const content = [
    `// Generated by Exhibit from ${ticketKey}. Plain Playwright — edit freely.`,
    `// Each test was recorded by the browser agent and replayed once without AI.`,
    `import { test, expect } from "@playwright/test";`,
    ``,
    blocks.join("\n\n"),
    ``,
  ].join("\n");

  return {
    fileName: `${ticketKey.toLowerCase()}.exhibit.spec.ts`,
    content,
    scenarioIds: usable.map((r) => r.scenarioId),
  };
}
